#!/usr/bin/env python3
"""Generate Go opcode definitions from mruby's include/mruby/ops.h.

Usage:
    python3 tools/genopcodes.py path/to/mruby/include/mruby/ops.h > bytecode/opcodes_gen.go

The generated file is committed so that the compiler does not depend on a
local mruby checkout at build time.
"""

import re
import sys

pattern = re.compile(r"^OPCODE\(([A-Za-z0-9_]+),\s*([A-Z]+)\)")


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2

    entries = []
    with open(sys.argv[1], "r", encoding="utf-8") as source:
        for line in source:
            match = pattern.match(line.strip())
            if match:
                entries.append((match.group(1), match.group(2)))

    if not entries:
        print("no opcodes found", file=sys.stderr)
        return 1

    print("// Code generated by tools/genopcodes.py; DO NOT EDIT.")
    print("//")
    print("// Source: mruby 4.0.0 include/mruby/ops.h")
    print()
    print("package bytecode")
    print()
    print("const (")
    for index, (name, _) in enumerate(entries):
        suffix = " Opcode = iota" if index == 0 else ""
        print(f"\tOp{name}{suffix}")
    print(")")
    print()
    print("// OpcodeCount is the number of opcodes in mruby 4.0.0.")
    print(f"const OpcodeCount = {len(entries)}")
    print()
    print("var opcodeInfo = [...]opcodeDesc{")
    for name, operands in entries:
        print(f'\t{{name: "{name}", operands: Operand{operands}}},')
    print("}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
